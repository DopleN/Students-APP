public class Student {
    public String name;
    public String id;
    public String phone;
    public String address;
    public boolean isChecked;

    public Student(String name, String id, String phone, String address, boolean isChecked) {
        this.name = name;
        this.id = id;
        this.phone = phone;
        this.address = address;
        this.isChecked = isChecked;
    }
}